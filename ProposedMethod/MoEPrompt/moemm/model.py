"""MoEPromptModel: MPLMM's PromptModel with a mixture-of-experts generator.

Baseline: a missing modality m is generated by one fixed function,
    G_base(x)[m] = Fusion_m^S( [P_G[m]; Translator^{s->m}(x_s) for s in S] )
shared by every sample (S = available sources).

Here (design A: base generator = always-on shared expert):
    x_hat[m] = G_base(x)[m] + tanh(gate_m) * sum_k p_k(x)[m] * expert_k(x)[m]
with the experts and router of moemm.experts. gate_m starts at 0, so at
initialisation the model computes exactly the baseline function (checked by
scripts/sanity_checks.py). The frozen MOSEI backbone and every other baseline
component are reused unchanged.

get_complete_data() is a table-driven rewrite of the baseline's seven
if-branches (same operations in the same order); forward() is copied from
MPLMM/src/model.py with the changes marked "# MoE".

forward(..., return_aux=True) also returns what the extra losses need:
features before the output layer (distillation), router weights (load
balance), and (generated, real) pairs for every missing modality
(reconstruction). The real target is detached and is only used by the loss.
"""

from types import SimpleNamespace

import torch
import torch.nn.functional as F
from torch import nn

from moemm.bridge import PromptModel, transfer_model
from moemm.config import MODEL_DEFAULTS, PRETRAINED_BACKBONE, dataset_cfg
from moemm.experts import MISSING, MOD_INDEX, MODALITIES, SOURCES, MoEGenerator

DEFAULT_MOE = {"enabled": True, "k": 3, "rank": 16, "router_hidden": 16, "tau": 1.0}

# Baseline fusion layer for (target, available sources), e.g. ("l", ("a", "v")) -> l_avp.
BASE_FUSION = {
    ("l", ("a", "v")): "l_avp", ("l", ("a",)): "l_ap", ("l", ("v",)): "l_vp",
    ("a", ("l", "v")): "a_lvp", ("a", ("l",)): "a_lp", ("a", ("v",)): "a_vp",
    ("v", ("l", "a")): "v_alp", ("v", ("l",)): "v_lp", ("v", ("a",)): "v_ap",
}

# Diagnostics only (scripts/diagnose.py): replace the generated features by
#   "oracle": the projected REAL modality (an upper bound for any generator)
#   "zero"  : zeros (how much the generated features contribute at all)
OVERRIDES = (None, "oracle", "zero")


class MoEPromptModel(PromptModel):
    def __init__(self, hyp_params, moe_cfg=None):
        super().__init__(hyp_params)
        self.moe_cfg = {**DEFAULT_MOE, **(moe_cfg or {})}
        self.generator_override = None
        if self.moe_cfg["enabled"]:
            cfg = self.moe_cfg
            self.moe = MoEGenerator(
                in_dims=(self.orig_d_l, self.orig_d_a, self.orig_d_v),
                seq_lens=(self.llen, self.alen, self.vlen),
                out_dim=self.prompt_dim,
                n_experts=cfg["k"], rank=cfg["rank"], router_hidden=cfg["router_hidden"],
                tau=cfg["tau"],
            )
            self.moe_gate = nn.Parameter(torch.zeros(3))

    def moe_parameters(self):
        return [p for n, p in self.named_parameters() if n.startswith("moe")]

    # ------------------------------------------------------------ generation
    def generate(self, m, inputs, available):
        """Baseline generator output for missing modality m (before its prompt)."""
        x = torch.cat(
            [self.generative_prompt[MOD_INDEX[m]]]
            + [getattr(self, f"{s}2{m}")(inputs[s])[0] for s in available], dim=1
        ).unsqueeze(dim=0)
        fusion = getattr(self, BASE_FUSION[(m, available)])
        return fusion(x.transpose(1, 2)).transpose(1, 2)

    def get_complete_data(self, x_l, x_a, x_v, missing_mode, moe_out=None, recon=None):
        """One sample. moe_out: [3] per-target MoE corrections [prompt_dim, T_m] or None.
        recon: list collecting (generated, real target) pairs, or None."""
        inputs = {"l": x_l.unsqueeze(0), "a": x_a.unsqueeze(0), "v": x_v.unsqueeze(0)}
        missing = MISSING[int(missing_mode)]
        out = {}
        for m in MODALITIES:
            if m not in missing:
                out[m] = getattr(self, f"proj_{m}")(inputs[m]) + getattr(self, f"prompt{m}_nm")
                continue
            available = tuple(s for s in SOURCES[m] if s not in missing)
            gen = self.generate(m, inputs, available)
            if self.generator_override == "oracle":
                gen = getattr(self, f"proj_{m}")(inputs[m])
            elif self.generator_override == "zero":
                gen = torch.zeros_like(gen)
            if moe_out is not None:
                j = MOD_INDEX[m]
                gen = gen + torch.tanh(self.moe_gate[j]) * moe_out[j].unsqueeze(0)
            if recon is not None:
                target = getattr(self, f"proj_{m}")(inputs[m]).detach()
                if target.shape != gen.shape:
                    raise RuntimeError(f"{m}: generated {tuple(gen.shape)} vs real {tuple(target.shape)}")
                recon.append((gen, target))
            out[m] = gen + getattr(self, f"prompt{m}_m")
        return out["l"], out["a"], out["v"]

    # --------------------------------------- copied from PromptModel, see header
    def forward(self, x_l, x_a, x_v, missing_mod, return_aux=False):  # MoE: return_aux
        if self.generator_override not in OVERRIDES:
            raise ValueError(f"generator_override must be one of {OVERRIDES}")
        missing_mod = torch.as_tensor(missing_mod, device=x_l.device).long()  # MoE

        x_l = F.dropout(x_l.transpose(1, 2), p=self.embed_dropout, training=self.training)
        x_a = x_a.transpose(1, 2)
        x_v = x_v.transpose(1, 2)

        moe_out, probs = None, None  # MoE
        if self.moe_cfg["enabled"]:
            moe_out, probs = self.moe(x_l, x_a, x_v, missing_mod)
        recon = [] if return_aux else None

        xx_l, xx_a, xx_v = [], [], []
        for idx in range(len(x_l)):
            x_l_temp, x_a_temp, x_v_temp = self.get_complete_data(
                x_l[idx], x_a[idx], x_v[idx], missing_mod[idx],
                None if moe_out is None else [o[idx] for o in moe_out], recon,  # MoE
            )
            xx_l.append(x_l_temp)
            xx_a.append(x_a_temp)
            xx_v.append(x_v_temp)
        xx_l, xx_a, xx_v = torch.cat(xx_l), torch.cat(xx_a), torch.cat(xx_v)

        proj_x_a = xx_a.permute(2, 0, 1)
        proj_x_v = xx_v.permute(2, 0, 1)
        proj_x_l = xx_l.permute(2, 0, 1)

        self.get_proj_matrix()
        batch_prompt = torch.stack(
            [torch.matmul(self.missing_type_prompt, self.mp[missing_mod[idx]])
             for idx in range(len(x_l))]
        )
        batch_prompt = batch_prompt.transpose(0, 1)

        h_l_with_as = self.trans_l_with_a(proj_x_l, proj_x_a, proj_x_a)
        h_l_with_vs = self.trans_l_with_v(proj_x_l, proj_x_v, proj_x_v)
        h_ls = torch.cat([h_l_with_as, h_l_with_vs], dim=2)
        h_ls = torch.cat([h_ls, batch_prompt[0].transpose(0, 1)], dim=0)
        h_ls = self.trans_l_mem(h_ls)
        if type(h_ls) == tuple:
            h_ls = h_ls[0]
        last_h_l = h_ls[-1]

        h_a_with_ls = self.trans_a_with_l(proj_x_a, proj_x_l, proj_x_l)
        h_a_with_vs = self.trans_a_with_v(proj_x_a, proj_x_v, proj_x_v)
        h_as = torch.cat([h_a_with_ls, h_a_with_vs], dim=2)
        h_as = torch.cat([h_as, batch_prompt[1].transpose(0, 1)], dim=0)
        h_as = self.trans_a_mem(h_as)
        if type(h_as) == tuple:
            h_as = h_as[0]
        last_h_a = h_as[-1]

        h_v_with_ls = self.trans_v_with_l(proj_x_v, proj_x_l, proj_x_l)
        h_v_with_as = self.trans_v_with_a(proj_x_v, proj_x_a, proj_x_a)
        h_vs = torch.cat([h_v_with_ls, h_v_with_as], dim=2)
        h_vs = torch.cat([h_vs, batch_prompt[2].transpose(0, 1)], dim=0)
        h_vs = self.trans_v_mem(h_vs)
        if type(h_vs) == tuple:
            h_vs = h_vs[0]
        last_h_v = h_vs[-1]
        last_hs = torch.cat([last_h_l, last_h_a, last_h_v], dim=1)

        last_hs_proj = self.proj2(
            F.dropout(F.relu(self.proj1(last_hs)), p=self.out_dropout, training=self.training)
        )
        last_hs_proj += last_hs
        output = self.out_layer(last_hs_proj)
        if not return_aux:
            return output
        return output, {  # MoE
            "features": last_hs_proj, "probs": probs, "modes": missing_mod, "recon": recon,
        }


# ------------------------------------------------------------ construction
def make_hyp_params(dataset, train_split):
    """The hyper-parameter namespace PromptModel expects (as built by MPLMM/main.py)."""
    orig_d_l, orig_d_a, orig_d_v = train_split.get_dim()
    return SimpleNamespace(
        **MODEL_DEFAULTS,
        orig_d_l=orig_d_l,
        orig_d_a=orig_d_a,
        orig_d_v=orig_d_v,
        seq_len=tuple(train_split.get_seq_len()),
        output_dim=dataset_cfg(dataset)["output_dim"],
        dataset=dataset,
    )


def build_model(dataset, train_split, moe_cfg, device):
    """MoEPromptModel with the MOSEI backbone loaded and frozen.

    transfer_model() (MPLMM) copies every backbone weight except the input
    projections and output head, and freezes what it copied. The moe* layers
    are new, so they stay trainable.
    """
    hyp_params = make_hyp_params(dataset, train_split)
    model = MoEPromptModel(hyp_params, moe_cfg).to(device)
    model = transfer_model(model, str(PRETRAINED_BACKBONE))
    return model, hyp_params


def from_legacy(path, hyp_params, device):
    """A baseline checkpoint (pickled PromptModel) as a MoEPromptModel without MoE."""
    legacy = torch.load(path, map_location=device, weights_only=False)
    model = MoEPromptModel(hyp_params, {"enabled": False}).to(device)
    model.load_state_dict(legacy.state_dict())  # strict: every weight must match
    return model.eval()


# ------------------------------------------------------------- checkpoints
def save_checkpoint(model, path, hyp_params, extra=None):
    path.parent.mkdir(parents=True, exist_ok=True)
    torch.save(
        {
            "state_dict": model.state_dict(),
            "hyp_params": vars(hyp_params),
            "moe_cfg": model.moe_cfg,
            "extra": extra or {},
        },
        path,
    )


def load_checkpoint(path, device):
    ckpt = torch.load(path, map_location=device, weights_only=False)
    model = MoEPromptModel(SimpleNamespace(**ckpt["hyp_params"]), ckpt["moe_cfg"]).to(device)
    model.load_state_dict(ckpt["state_dict"])
    return model.eval(), ckpt
